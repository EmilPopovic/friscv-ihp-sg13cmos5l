"""Write <work>/gen/: hbt_defines.svh, hbt_gen.svh, hbt_dut.svh and sources.f."""

from __future__ import annotations

import math
import re
import subprocess
from pathlib import Path

from . import timing
from .config import CORNERS, REPO_ROOT, TOOL_DIR, Config, ConfigError
from .rtl import Controller

TB_DIR = TOOL_DIR / "tb"
TB_SOURCES = ("hbt_pkg.sv", "hbt_delay_model.sv", "hbt_tdelay.sv", "hbt_shchk.sv",
              "hbt_board.sv", "hbt_hyperram.sv", "hbt_tb.sv")
DELAY_PORTS = ("clk_i", "enable_i", "delay_i", "clk_o")

# the hyper_* pad ports connect by name
TB_PORTS = {
    "clk_phy_i": "clk", "rst_phy_ni": "rst_n", "clk_sys_i": "clk", "rst_sys_ni": "rst_n",
    "test_mode_i": "1'b0", "axi_req_i": "axi_req", "axi_rsp_o": "axi_rsp",
    "reg_req_i": "reg_req", "reg_rsp_o": "reg_rsp",
}

REGISTERS = ("t_latency_access", "en_latency_additional", "t_burst_max", "t_rx_clk_delay",
             "t_tx_clk_delay", "address_space")

DESIGN_UNIT = re.compile(r"^\s*(?:module|package|interface)\s+(?:automatic\s+|static\s+)?(\w+)",
                         re.M)
COMMENT = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)
IDENTIFIER = re.compile(r"\b[A-Za-z_]\w*\b")


def generate(cfg: Config, ctl: Controller, work: Path) -> Path:
    out = Path(work) / "gen"
    out.mkdir(parents=True, exist_ok=True)

    _write_if_changed(out / "hbt_defines.svh", defines(cfg, ctl))
    _write_if_changed(out / "hbt_gen.svh", constants(cfg, ctl, work))
    _write_if_changed(out / "hbt_dut.svh", dut_instance(cfg, ctl))

    tb = [str(TB_DIR / name) for name in TB_SOURCES]
    rtl = rtl_file_list(cfg, [*tb, str(out / "hbt_dut.svh"), str(out / "hbt_gen.svh")])
    sources = [f"+incdir+{out}", f"+incdir+{TB_DIR}", *rtl, *tb]
    _write_if_changed(out / "sources.f", "\n".join(sources) + "\n")

    return out


def sweep_startup_cycles(cfg: Config, device: dict, period_ns: float | None = None) -> int:
    """Just past the device's power-up time tVCS."""
    if cfg.sweep.startup_cycles:
        return cfg.sweep.startup_cycles

    cycles = device["tvcs"] / (period_ns or cfg.period_ns) * 1.08
    return math.ceil(cycles / 100) * 100


def defines(cfg: Config, ctl: Controller) -> str:
    unsupported = [p for p in ctl.delay_ports if p not in DELAY_PORTS]
    if unsupported:
        raise ConfigError(f"configurable_delay ports {', '.join(unsupported)} are not supported")

    unknown = [name for name in cfg.rst_cfg if name not in ctl.cfg_fields]
    if unknown:
        raise ConfigError(f"rst_cfg: hyper_cfg_t has no {', '.join(unknown)} "
                          f"(fields: {', '.join(ctl.cfg_fields)})")

    phy = (cfg.phy_path or ctl.phy_path(cfg.phys)).replace("{p}", "p")
    overrides = " ".join(f"cfg.{name} = {int(value)};" for name, value in cfg.rst_cfg.items())

    lines = [f"`define HBT_PHY(p) i_hyperbus.{phy}",
             f"`define HBT_RST_CFG_OVERRIDES(cfg) {overrides}"]
    if cfg.clock == "delayed":
        lines.append("`define HBT_TX_DELAYED")
    if ctl.cs_clock == "core_fall":
        lines.append("`define HBT_CS_CORE_FALL")
    if "enable_i" in ctl.delay_ports:
        lines.append("`define HBT_DL_ENABLE")

    return "`ifndef HBT_DEFINES\n`define HBT_DEFINES\n" + "\n".join(lines) + "\n`endif\n"


def constants(cfg: Config, ctl: Controller, work: Path) -> str:
    delay = timing.delay_line(cfg, ctl, work)
    pads = timing.pads(cfg, work)
    chip = timing.chip_delays(cfg, work)
    registers = {**ctl.registers, **cfg.reg_map}
    reset = {**ctl.reset, **cfg.rst_cfg}

    sv = _SvWriter(f"// Generated by hbt from {cfg.path.relative_to(REPO_ROOT)}")
    sv.param("string", "HBT_SYSTEM", _sv_string(cfg.name))

    ints = {
        "NUM_PHYS": cfg.phys, "NUM_CHIPS": cfg.chips,
        "AXI_AW": cfg.axi.addr, "AXI_DW": cfg.axi.data, "AXI_IW": cfg.axi.id,
        "AXI_UW": cfg.axi.user, "REG_AW": cfg.reg_bus.addr, "REG_DW": cfg.reg_bus.data,
        "MIN_FREQ_MHZ": cfg.min_freq_mhz,
        "PHY_STARTUP_CYCLES": cfg.phy_startup_cycles or ctl.startup_default,
        "RST_TX_CODE": reset.get("t_tx_clk_delay", 0),
        "RST_RX_CODE": reset.get("t_rx_clk_delay", 0),
        "DEF_BUS_IDLE": ("keeper", "pulldown", "pullup").index(cfg.board.idle),
        "DEF_LATENCY": cfg.device.latency,
        "DEF_FIXED_LATENCY": int(cfg.device.fixed_latency),
        "DEF_PROGRAM_CR0": int(cfg.device.program_cr0),
        "NUM_CODES": ctl.num_codes, "NUM_LOADS": len(pads.loads_pf),
    }
    for name, value in ints.items():
        sv.param("int unsigned", f"HBT_{name}", value)

    for name in REGISTERS:
        sv.param("int unsigned", f"HBT_REG_{name.upper()}", registers[name])

    for name, value in (("MEM_BASE", cfg.mem_base), ("CHIP_SPACE", cfg.chip_size),
                        ("REG_BASE", cfg.reg_base)):
        sv.param("longint unsigned", f"HBT_{name}", f"64'h{value:x}")

    reals = {
        "DEF_TCK_NS": cfg.period_ns, "CK_DIV": 2.0 if cfg.clock == "divided" else 1.0,
        "DEF_LOAD_PF": cfg.board.load_pf, "DEF_FLIGHT_NS": cfg.board.flight_ns,
        "DEF_FLIGHT_SKEW_NS": cfg.board.skew_ns, "DEF_JITTER_NS": cfg.board.jitter_ns,
    }
    for name, value in reals.items():
        sv.param("real", f"HBT_{name}", value)

    sv.param("string", "HBT_DEF_MEM", _sv_string(cfg.device.part))
    sv.param("string", "HBT_DLINE_SRC", _sv_string(delay.source))
    sv.param("string", "HBT_PAD_SRC", _sv_string(pads.source))

    sv.param("real", f"HBT_DLINE_RISE [3][{ctl.num_codes}]", _sv_array(delay.rise))
    sv.param("real", f"HBT_DLINE_FALL [3][{ctl.num_codes}]", _sv_array(delay.fall))
    sv.param("real", "HBT_LOADS_PF [HBT_NUM_LOADS]", _sv_array(pads.loads_pf, "{:.3f}"))
    for arc in timing.PAD_ARCS:
        sv.param("real", f"HBT_PAD_{arc.upper()} [3][HBT_NUM_LOADS][2]", _sv_array(pads.arcs[arc]))

    sv.lines += _chip_delays_function(chip)
    sv.lines += _mem_profile_function(timing.device_parts(cfg))

    return sv.text()


def _chip_delays_function(chip: timing.ChipDelays) -> list[str]:
    lines = ["function automatic hbt_chip_delays_t chip_delays(int unsigned corner);",
             "    hbt_chip_delays_t d;",
             "    case (corner)"]

    for index in range(len(CORNERS)):
        lines.append(f"        {index}: begin d.src = {_sv_string(chip.sources[index])};")
        lines += [f"            d.{name} = {chip.values[index][name]:.4f};"
                  for name in timing.CHIP_FIELDS]
        lines.append("        end")

    return lines + ["        default: ;", "    endcase", "    return d;", "endfunction"]


def _mem_profile_function(parts: dict[str, dict]) -> list[str]:
    lines = ["function automatic hbt_mem_profile_t mem_profile(string name);",
             "    hbt_mem_profile_t p;",
             "    case (name)"]

    for name, part in sorted(parts.items()):
        lines.append(f"        {_sv_string(name)}: begin p.name = {_sv_string(name)};")
        for field in timing.DEVICE_FIELDS:
            value = int(part[field]) if field.endswith("_bytes") else float(part[field])
            lines.append(f"            p.{field} = {value};")
        lines.append("        end")

    known = ", ".join(sorted(parts))
    default = f'        default: $fatal(1, "unknown HyperRAM part %s (known: {known})", name);'

    return lines + [default, "    endcase", "    return p;", "endfunction"]


def dut_instance(cfg: Config, ctl: Controller) -> str:
    params = {
        "NumChips": "NumChips", "NumPhys": "NumPhys",
        ctl.clock_param: ctl.clock_param_value(cfg.clock),
        "AxiAddrWidth": "HBT_AXI_AW", "AxiDataWidth": "DW", "AxiIdWidth": "HBT_AXI_IW",
        "AxiUserWidth": "HBT_AXI_UW",
        "axi_req_t": "hbt_axi_req_t", "axi_rsp_t": "hbt_axi_resp_t",
        "axi_w_chan_t": "hbt_axi_w_chan_t", "axi_b_chan_t": "hbt_axi_b_chan_t",
        "axi_ar_chan_t": "hbt_axi_ar_chan_t", "axi_r_chan_t": "hbt_axi_r_chan_t",
        "axi_aw_chan_t": "hbt_axi_aw_chan_t",
        "RegAddrWidth": "HBT_REG_AW", "RegDataWidth": "HBT_REG_DW",
        "reg_req_t": "hbt_reg_req_t", "reg_rsp_t": "hbt_reg_rsp_t",
        "axi_rule_t": f"axi_pkg::xbar_rule_{cfg.axi.addr}_t",
        "MinFreqMHz": "HBT_MIN_FREQ_MHZ",
        "RstChipBase": "HBT_MEM_BASE", "RstChipSpace": "HBT_CHIP_SPACE",
        "RstCfg": "hyper_rst_cfg()",
        "PhyStartupCycles": "PhyStartupCycles",
    }

    for name, value in cfg.params.items():
        if name not in ctl.params:
            raise ConfigError(f"params.{name}: hyperbus has no such parameter "
                              f"(it has {', '.join(ctl.params)})")
        params[name] = int(value) if isinstance(value, bool) else value

    unknown = [p for p in ctl.ports if p not in TB_PORTS and not p.startswith("hyper_")]
    if unknown:
        raise ConfigError(f"hyperbus has ports the testbench does not know: {', '.join(unknown)}")

    param_lines = [f"    .{name:<17}( {value} )" for name, value in params.items()
                   if name in ctl.params]
    port_lines = [f"    .{port:<17}( {TB_PORTS[port]} )" if port in TB_PORTS else f"    .{port}"
                  for port in ctl.ports]

    return ("hyperbus #(\n" + ",\n".join(param_lines) + "\n) i_hyperbus (\n"
            + ",\n".join(port_lines) + "\n);\n")


def rtl_file_list(cfg: Config, roots: list[str]) -> list[str]:
    """The files declaring what the roots use, transitively, minus other configurable_delays."""
    lines = list(cfg.files) or _bender_file_list(cfg)
    sources = [f for f in lines if not f.startswith("+") and f.endswith((".sv", ".v"))]

    declared_in: dict[str, str] = {}
    names_used: dict[str, set[str]] = {}

    for path in sources + roots:
        try:
            text = COMMENT.sub(" ", Path(path).read_text(errors="replace"))
        except FileNotFoundError:
            raise ConfigError(f"file list entry not found: {path}") from None

        units = DESIGN_UNIT.findall(text)
        if path in sources and "configurable_delay" in units:
            continue

        for unit in units:
            declared_in.setdefault(unit, path)
        names_used[path] = set(IDENTIFIER.findall(text))

    needed: set[str] = set()
    pending = list(roots)
    while pending:
        for name in names_used.get(pending.pop(), ()):
            path = declared_in.get(name)
            if path and path not in needed:
                needed.add(path)
                pending.append(path)

    kept = [f for f in lines if f.startswith("+") or f in needed]

    for line in kept:
        if line.startswith("+") and not line.startswith("+incdir+"):
            continue

        path = Path(line.removeprefix("+incdir+")).resolve()
        if not path.is_relative_to(REPO_ROOT):
            raise ConfigError(f"{path} is outside the repository (check Bender.local and .bender)")

    return kept


def _bender_file_list(cfg: Config) -> list[str]:
    command = [cfg.tools.bender, "script", "flist-plus"]
    for target in cfg.targets:
        command += ["-t", target]

    try:
        result = subprocess.run(command, cwd=cfg.bender, capture_output=True, text=True)
    except FileNotFoundError:
        raise ConfigError(f"{cfg.tools.bender} not found (run inside `nix develop`)") from None

    if result.returncode:
        raise ConfigError(f"bender failed in {cfg.bender}:\n{result.stderr.strip()}")

    return [line.strip() for line in result.stdout.splitlines() if line.strip()]


class _SvWriter:
    def __init__(self, header: str):
        self.lines = [header]

    def param(self, sv_type: str, name: str, value) -> None:
        self.lines.append(f"localparam {sv_type} {name} = {value};")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def _sv_string(value) -> str:
    return '"' + str(value).replace("\\", "\\\\").replace('"', "'") + '"'


def _sv_array(values, fmt: str = "{:.4f}") -> str:
    if not isinstance(values, (list, tuple)):
        return fmt.format(values)

    return "'{" + ", ".join(_sv_array(v, fmt) for v in values) + "}"


def _write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
